-- | Assemble the temporary Docker build context for a static site release.
--
-- The image is generated, never hand-written (MasterPlan Integration Point 3):
-- an Nginx base image that serves the built files from
-- @/usr/share/nginx/html@ on port 8080, with the generated server config copied
-- over Nginx's @default.conf@. 'withStaticImageContext' writes that context into
-- a temp directory and hands the path to a continuation (typically
-- 'Nagare.Image.buildImage'); the temp directory is removed on exit, so a
-- partial failure leaves nothing behind. 'writeStaticContext' is the shared
-- durable writer beneath it: it stages the context beside its destination,
-- refuses symlinks, and returns the context's content digest.
--
-- The layout written is:
--
-- > <ctx>/Dockerfile
-- > <ctx>/nginx.conf
-- > <ctx>/site/...        (the prepared static output)
module Nagare.Static.Image
  ( staticDockerfile
  , withStaticImageContext
  , writeStaticContext
  , StaticContextError (..)
  , renderStaticContextError
  )
where

import Control.Exception (onException)
import Data.Bits ((.&.))
import Data.ByteString (ByteString)
import Data.ByteString qualified as BS
import Data.Generics.Labels ()
import Data.List (isPrefixOf)
import Data.Text qualified as T
import Nagare.Dsl.Prelude
import Nagare.Dsl.Static.Render (renderNginxConfig)
import Nagare.Dsl.Static.Types (StaticSite)
import Nagare.Static.Build (PreparedStaticOutput (..))
import Nagare.Static.ContentDigest (ContentDigest, digestContextTree)
import System.Directory
  ( canonicalizePath
  , createDirectory
  , createDirectoryIfMissing
  , doesPathExist
  , listDirectory
  , makeAbsolute
  , removeDirectoryRecursive
  , renameDirectory
  )
import System.FilePath (addTrailingPathSeparator, takeDirectory, takeFileName, (</>))
import System.IO.Temp (createTempDirectory, withSystemTempDirectory)
import System.Posix.Files
  ( fileMode
  , getSymbolicLinkStatus
  , isDirectory
  , isRegularFile
  , isSymbolicLink
  , ownerExecuteMode
  , setFileMode
  )

-- | The generated Dockerfile for every static-site release. The Nginx config
-- generated by EP-13 listens on 8080, the port Knative routes to.
staticDockerfile :: ByteString
staticDockerfile =
  BS.intercalate
    "\n"
    [ "FROM nginx:1.27-alpine"
    , "COPY nginx.conf /etc/nginx/conf.d/default.conf"
    , "COPY site/ /usr/share/nginx/html/"
    , "EXPOSE 8080"
    , ""
    ]

-- | Why a build context could not be written.
data StaticContextError
  = -- | the destination already exists; a final context is never replaced
    ContextDestinationExists !FilePath
  | -- | source and destination are the same tree or nested in each other
    ContextPathsOverlap !FilePath !FilePath
  | -- | a symlink or special file in the output (path)
    ContextUnsupportedEntry !FilePath
  deriving stock (Eq, Show)

renderStaticContextError :: StaticContextError -> Text
renderStaticContextError = \case
  ContextDestinationExists p ->
    "destination already exists: " <> T.pack p <> " (choose a new path; existing artifacts are never replaced)"
  ContextPathsOverlap source destination ->
    "destination overlaps the static output: " <> T.pack destination <> " and " <> T.pack source
  ContextUnsupportedEntry p ->
    "static output contains a symlink or special file: "
      <> T.pack p
      <> " (dereference it first, e.g. cp -RL OUTPUT NEW_DIR, and point the site at the copy)"

-- | Write the build context for @site@ from its @prepared@ output at
-- @destination@ and return the context's content digest. The context is staged
-- in a sibling directory and renamed into place only when complete, so a failed
-- or interrupted write leaves no destination behind. Regular files and
-- directories are copied byte for byte (dotfiles, structure and the executable
-- bit preserved); a symlink or special file is refused.
writeStaticContext ::
  StaticSite -> PreparedStaticOutput -> FilePath -> IO (Either StaticContextError ContentDigest)
writeStaticContext site prepared destination0 = do
  destination <- makeAbsolute destination0
  exists <- doesPathExist destination
  if exists
    then pure (Left (ContextDestinationExists destination))
    else do
      source <- canonicalizePath (prepared ^. #outputDirectory)
      let parent = takeDirectory destination
      createDirectoryIfMissing True parent
      canonicalParent <- canonicalizePath parent
      let resolved = canonicalParent </> takeFileName destination
      if nested source resolved || nested resolved source
        then pure (Left (ContextPathsOverlap source resolved))
        else do
          staging <- createTempDirectory parent ".nagare-context"
          let stage = do
                createDirectory (staging </> "site")
                refused <- copyTree source (staging </> "site")
                case refused of
                  Just path -> pure (Left (ContextUnsupportedEntry path))
                  Nothing -> do
                    BS.writeFile (staging </> "nginx.conf") (renderNginxConfig site)
                    BS.writeFile (staging </> "Dockerfile") staticDockerfile
                    digest <- digestContextTree staging
                    renameDirectory staging destination
                    pure (Right digest)
          result <- stage `onException` removeDirectoryRecursive staging
          case result of
            Left _ -> removeDirectoryRecursive staging
            Right _ -> pure ()
          pure result
  where
    nested outer inner =
      addTrailingPathSeparator outer `isPrefixOf` addTrailingPathSeparator inner

-- | Copy the contents of @from@ into the existing directory @to@. Returns the
-- first path that is neither a regular file nor a directory.
copyTree :: FilePath -> FilePath -> IO (Maybe FilePath)
copyTree sourceDir targetDir = do
  names <- listDirectory sourceDir
  go names
  where
    go [] = pure Nothing
    go (name : rest) = do
      let source = sourceDir </> name
          target = targetDir </> name
      status <- getSymbolicLinkStatus source
      if isSymbolicLink status
        then pure (Just source)
        else
          if isDirectory status
            then do
              createDirectory target
              nested <- copyTree source target
              maybe (go rest) (pure . Just) nested
            else
              if isRegularFile status
                then do
                  BS.readFile source >>= BS.writeFile target
                  setFileMode target (if fileMode status .&. ownerExecuteMode /= 0 then 0o755 else 0o644)
                  go rest
                else pure (Just source)

-- | Build the temp image context for @site@ from its @prepared@ output, then run
-- @action@ with the context directory path. The directory is cleaned up when
-- @action@ returns or throws.
withStaticImageContext ::
  StaticSite -> PreparedStaticOutput -> (FilePath -> IO a) -> IO a
withStaticImageContext site prepared action =
  withSystemTempDirectory "nagare-static-ctx" $ \scratch -> do
    let ctx = scratch </> "context"
    writeStaticContext site prepared ctx
      >>= either (ioError . userError . T.unpack . renderStaticContextError) (const (pure ()))
    action ctx
